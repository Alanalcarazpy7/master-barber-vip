const $ = (selector, parent = document) => parent.querySelector(selector);
const $$ = (selector, parent = document) => Array.from(parent.querySelectorAll(selector));

function whatsappUrl(text = MB.message) {
  return `https://wa.me/${MB.whatsapp}?text=${encodeURIComponent(text)}`;
}

function setImage(id, image) {
  const img = $(id);
  if (!img || !image) return;
  img.src = image.src || image.fallback;
  img.onerror = () => {
    if (image.fallback && img.src.indexOf(image.fallback) === -1) img.src = image.fallback;
  };
}

function imageTag(image, alt, className = "") {
  const src = image?.src || image?.fallback || "";
  const fallback = image?.fallback || "";
  return `<img class="${className}" src="${src}" data-fallback="${fallback}" alt="${alt}" loading="lazy" />`;
}

function hydrateImages() {
  $$('img[data-fallback]').forEach((img) => {
    img.onerror = () => {
      const fallback = img.getAttribute('data-fallback');
      if (fallback && img.src.indexOf(fallback) === -1) img.src = fallback;
    };
  });
}

