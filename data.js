function boot() {
  setImage('#header-logo', MB.assets.headerLogo);
  setImage('#mobile-logo', MB.assets.mainLogo);
  setImage('#footer-logo', MB.assets.mainLogo);
  setImage('#hero-logo', MB.assets.mainLogo);
  setImage('#hero-image', MB.assets.hero);
  renderBenefits();
  renderServices();
  renderProcess();
  renderReviews();
  renderFilters();
  renderGallery();
  renderFaqs();
  bindNavigation();
  bindCtas();
  bindHeader();
  hydrateImages();
  observeReveals();
  renderSchema();

  const lightbox = $('#lightbox');
  const close = $('#lightbox-close');
  if (close) close.addEventListener('click', closeLightbox);
  if (lightbox) lightbox.addEventListener('click', (e) => { if (e.target === lightbox) closeLightbox(); });
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeLightbox(); });
}

document.addEventListener('DOMContentLoaded', boot);
