function renderGallery(filter = 'Todos') {
  const grid = $('#gallery-grid');
  if (!grid) return;
  const items = filter === 'Todos' ? MB.gallery : MB.gallery.filter((item) => item.tag === filter);
  grid.innerHTML = items.map((item, idx) => `
    <button class="gallery-item reveal delay-${idx % 3}" type="button" data-title="${item.title}" data-src="${item.src}" data-fallback="${item.fallback}">
      ${imageTag(item, item.title)}
      <span>${item.title}</span>
    </button>
  `).join('');
  hydrateImages();
  bindGallery();
}

function renderFilters() {
  const wrap = $('#gallery-filters');
  if (!wrap) return;
  const tags = ['Todos', ...new Set(MB.gallery.map((item) => item.tag))];
  wrap.innerHTML = tags.map((tag, idx) => `<button class="chip ${idx === 0 ? 'active' : ''}" type="button" data-filter="${tag}">${tag}</button>`).join('');
  $$('.chip', wrap).forEach((btn) => {
    btn.addEventListener('click', () => {
      $$('.chip', wrap).forEach((b) => b.classList.remove('active'));
      btn.classList.add('active');
      renderGallery(btn.dataset.filter);
      observeReveals();
    });
  });
}

function renderFaqs() {
  const wrap = $('#faq-list');
  if (!wrap) return;
  wrap.innerHTML = MB.faqs.map((faq, idx) => `
    <article class="faq-item reveal delay-${idx % 3}">
      <button type="button" aria-expanded="false"><span>${faq.q}</span><b>+</b></button>
      <p>${faq.a}</p>
    </article>
  `).join('');
  $$('.faq-item button', wrap).forEach((btn) => {
    btn.addEventListener('click', () => {
      const item = btn.closest('.faq-item');
      const isOpen = item.classList.toggle('open');
      btn.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
      btn.querySelector('b').textContent = isOpen ? '−' : '+';
    });
  });
}

function bindGallery() {
  const lightbox = $('#lightbox');
  const lightboxImg = $('#lightbox-img');
  const caption = $('#lightbox-caption');
  if (!lightbox || !lightboxImg) return;

  $$('.gallery-item').forEach((btn) => {
    btn.addEventListener('click', () => {
      const src = btn.dataset.src;
      const fallback = btn.dataset.fallback;
      lightboxImg.src = src;
      lightboxImg.onerror = () => {
        if (fallback && lightboxImg.src.indexOf(fallback) === -1) lightboxImg.src = fallback;
      };
      lightboxImg.alt = btn.dataset.title || 'Imagen de Master Barber';
      if (caption) caption.textContent = btn.dataset.title || '';
      lightbox.classList.add('open');
      lightbox.setAttribute('aria-hidden', 'false');
      document.body.classList.add('no-scroll');
    });
  });
}

function closeLightbox() {
  const lightbox = $('#lightbox');
  if (!lightbox) return;
  lightbox.classList.remove('open');
  lightbox.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('no-scroll');
}

function bindNavigation() {
  const menu = $('#mobile-menu');
  const toggle = $('#menu-toggle');
  const close = $('#menu-close');
  const openMenu = () => {
    if (!menu || !toggle) return;
    menu.classList.add('open');
    menu.setAttribute('aria-hidden', 'false');
    toggle.setAttribute('aria-expanded', 'true');
    document.body.classList.add('no-scroll');
  };
  const closeMenu = () => {
    if (!menu || !toggle) return;
    menu.classList.remove('open');
    menu.setAttribute('aria-hidden', 'true');
    toggle.setAttribute('aria-expanded', 'false');
    document.body.classList.remove('no-scroll');
  };
  if (toggle) toggle.addEventListener('click', openMenu);
  if (close) close.addEventListener('click', closeMenu);
  if (menu) {
    menu.addEventListener('click', (e) => {
      if (e.target === menu || e.target.closest('a')) closeMenu();
    });
  }

  $$('a[href^="#"]').forEach((link) => {
    link.addEventListener('click', (e) => {
      const href = link.getAttribute('href');
      if (!href || href === '#') return;
      const target = $(href);
      if (!target) return;
      e.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
  });
}

function bindCtas() {
  $$('[data-whatsapp]').forEach((link) => {
    link.setAttribute('href', whatsappUrl());
    link.setAttribute('target', '_blank');
    link.setAttribute('rel', 'noopener');
  });
  const maps = $('#maps-link');
  if (maps) maps.href = MB.maps;
  const review = $('#review-link');
  if (review) review.href = MB.reviewUrl;
  const phone = $('#contact-phone');
  if (phone) phone.textContent = MB.phone;
  const year = $('#year');
  if (year) year.textContent = new Date().getFullYear();
}

function bindHeader() {
  const header = $('#site-header');
  if (!header) return;
  const onScroll = () => header.classList.toggle('scrolled', window.scrollY > 20);
  onScroll();
  window.addEventListener('scroll', onScroll, { passive: true });
}

function observeReveals() {
  const items = $$('.reveal:not(.is-visible)');
  if (!('IntersectionObserver' in window)) {
    items.forEach((item) => item.classList.add('is-visible'));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });
  items.forEach((item) => observer.observe(item));
}

